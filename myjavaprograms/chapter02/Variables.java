package chapter02;

public class Variables {

	public static void main(String[] args) {
		/*
		 * Data types: byte, short, int, long Floating types: float, double Other types:
		 * boolean, char -String-
		 */

		// Declaration and Definition of Variables
		int number = 3;
		double x, y;
		String name = "Sherlock", lastname = "Holmes";
		char character = 'i';

		// Assigning value
		number = 34;
		x = 0.9;
		y = -3.4;
		character = 'a';

		// printing variables

		System.out.println(x);
		System.out.println(name + lastname);
		System.out.println(name + " " + lastname);

	}

}
